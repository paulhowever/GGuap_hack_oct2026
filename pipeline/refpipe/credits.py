import argparse
from pathlib import Path

from refpipe import paths
from refpipe.errors import RefpipeError
from refpipe.meta import Meta, Work, load_meta

HEADER = "# Credits\n\nGenerated by `refpipe credits` from `songs/*/meta.yaml`. Do not edit by hand.\n"


def work_line(label: str, work: Work) -> str:
    parts = [f"«{work.title}»", work.author, work.license]
    if work.license_url:
        parts.append(work.license_url)
    if work.source:
        parts.append(f"source: {work.source}")
    return f"- {label}: " + ", ".join(parts)


def song_section(song_id: str, meta: Meta) -> str:
    rows = [
        f"## {meta.title} — {meta.artist} (`{song_id}`)",
        "",
        work_line("Music and lyrics", meta.license.music),
        work_line("Recording", meta.license.recording),
    ]
    if meta.vocalists:
        rows.append("- Vocals: " + ", ".join(v.name for v in meta.vocalists))
    if meta.license.changes:
        rows.append("- Changes: " + "; ".join(meta.license.changes))
    if meta.source.origin == "ultrasinger":
        rows.append("- Reference notes: generated with UltraSinger (MIT), checked by hand")
    rows.append(f"- Attribution: {meta.license.attribution}")
    return "\n".join(rows)


def render_credits(songs_dir: Path) -> str:
    if not Path(songs_dir).is_dir():
        raise RefpipeError(f"not a songs directory: {songs_dir}")
    metas = sorted(Path(songs_dir).glob("*/meta.yaml"))
    return HEADER + "".join(f"\n{song_section(p.parent.name, load_meta(p))}\n" for p in metas)


def cmd(args: argparse.Namespace) -> int:
    text = render_credits(args.songs)
    try:
        args.out.write_text(text, encoding="utf-8")
    except OSError as exc:
        raise RefpipeError(f"{args.out}: {exc}") from exc
    print(f"{args.out}: {text.count(chr(10) + '## ')} songs")
    return 0


def add_parser(sub) -> None:
    p = sub.add_parser("credits", help="generate CREDITS.md from songs/*/meta.yaml")
    p.add_argument("--songs", type=Path, default=paths.SONGS_DIR)
    p.add_argument("--out", type=Path, default=paths.CREDITS_MD)
    p.set_defaults(func=cmd)
